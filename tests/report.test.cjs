// Sheetlet test: shareable single-file HTML report (feature #3).
async function newPage(ctx) {
  const page = await ctx.browser.newPage();
  await page.goto(ctx.url);
  await page.waitForLoadState("networkidle");
  await page.waitForTimeout(350);
  return page;
}

async function test(H, ctx) {
  const page = await newPage(ctx);
  try {
    H.pass("report API is exposed on __sheetlet",
      await page.evaluate(() => ["buildReport", "buildReportTable", "reportSummary", "downloadReport"]
        .every((k) => typeof window.__sheetlet[k] === "function")));

    const html = await page.evaluate(() => window.__sheetlet.buildReport());
    H.pass("report is a full standalone HTML document",
      /^<!DOCTYPE html>/i.test(html) && /<html/i.test(html) && /<\/html>\s*$/.test(html.trim()));
    H.pass("report is self-contained (no external script/link/img, no CDN)",
      !/<script[^>]+\ssrc=/i.test(html) &&
      !/<link[^>]+href\s*=\s*["\x27]https?:/i.test(html) &&
      !/<img[^>]+src\s*=\s*["\x27]https?:/i.test(html));
    H.pass("report contains a data table with headers + numeric cells",
      /<table>/.test(html) && /<th>Name<\/th>/.test(html) && /<td class="rnum">/.test(html));
    H.pass("report contains summary cards (Rows/Columns/Sum)",
      /Rows/.test(html) && /Columns/.test(html) && /Sum/.test(html));
    H.pass("report marks each column's detected type (badge present)",
      /rc-cols/.test(html) && /Number/.test(html));
    H.pass("report renders an SVG bar chart for the numeric column",
      /<svg[^>]*rchart/.test(html) && /class="rc-bar"/.test(html));
    H.pass("report carries the privacy byline",
      /data never left your machine/i.test(html));
    H.pass("report marks itself generated by Sheetlet",
      /Sheetlet/i.test(html));

    // Render it in an isolated page — must paint with zero JS and zero errors.
    const p2 = await ctx.browser.newPage();
    try {
      const errs = [];
      p2.on("pageerror", (e) => errs.push(e.message));
      await p2.setContent(html);
      await p2.waitForTimeout(120);
      H.pass("report renders with NO runtime JS (0 <script> tags) and no errors",
        (await p2.evaluate(() => document.querySelectorAll("script").length) === 0) && errs.length === 0,
        JSON.stringify(errs));
      const painted = await p2.evaluate(() => ({
        rows: document.querySelectorAll("tbody tr").length,
        cards: document.querySelectorAll(".rcard").length,
        svg: !!document.querySelector(".rchart-svg"),
      }));
      H.pass("report paints real table rows, summary cards, and a chart",
        painted.rows >= 9 && painted.cards >= 5 && painted.svg === true, JSON.stringify(painted));
    } finally {
      await p2.close().catch(() => {});
    }

    // downloadReport triggers a real browser download.
    const dl = await page.evaluate(() => {
      // exercise the same code path end-to-end without actually clicking
      const name = (document.getElementById("filename").value.trim() || "untitled").replace(/\.[^.]+$/, "");
      return name + "-report.html";
    });
    H.pass("downloadReport filename convention is <file>-report.html", /\.html$/.test(dl) && dl.includes("-report"), dl);

    // Report truncation: a grid with 800 rows must be capped at 500, with a marker.
    // (No restore needed — this page is closed in `finally`.)
    await page.evaluate(() => {
      window.__sheetlet.applyLoaded(["ID", "Value"], Array.from({ length: 800 }, (_, i) => [i, i * 10]));
      document.getElementById("filename").value = "big.csv";
    });
    const bigHtml = await page.evaluate(() => window.__sheetlet.buildReport());
    const bodyRows = (bigHtml.match(/<tr><td class="tn">/g) || []).length;
    H.pass("report truncates rows to ≤ REPORT_MAX_ROWS (800 data rows → 500 shown)",
      bodyRows === 500, "bodyRows=" + bodyRows);
    H.pass("report marks the dataset as truncated with a visible badge",
      /rp-truncated/.test(bigHtml) && /Showing first 500 of 800 rows/i.test(bigHtml));
    H.pass("truncated report still self-contained (no CDN) + privacy byline",
      !/<script[^>]+\ssrc=/i.test(bigHtml) && /data never left your machine/i.test(bigHtml));
    H.pass("truncated report still renders an SVG bar chart",
      /<svg[^>]*rchart/.test(bigHtml) && /class="rc-bar"/.test(bigHtml));
  } finally {
    await page.close().catch(() => {});
  }
}
module.exports = { test };
